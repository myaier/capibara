import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes("--check");
const chunks = JSON.parse(await readFile(join(root, "client-chunks.json"), "utf8"));

for (const chunk of chunks) {
  const result = await build({
    absWorkingDir: root, entryPoints: [chunk.entry], bundle: true, format: "cjs", jsx: "automatic",
    platform: "neutral", target: "es2020", supported: { "async-await": false }, packages: "external",
    treeShaking: true, loader: { ".webp": "dataurl" }, minifyWhitespace: true, minifySyntax: true, minifyIdentifiers: false,
    write: false, logLevel: "silent",
  });
  // Match Paseo's eager host-module interop for Hermes, including renamed helper loop variables.
  const body = result.outputFiles[0].text.replace(/get:\s*\(\)\s*=>\s*(from\d*)\[(key\d*)\]/g, "value:$1[$2]");
  const code = `(function(require) {\nconst module = { exports: {} };\nconst exports = module.exports;\n${body}\nreturn module.exports;\n})`;
  const manifest = { name: chunk.name, hash: createHash("sha256").update(code).digest("hex").slice(0, 16), api: chunk.api, bytes: Buffer.byteLength(code) };
  const outputs = [
    [`server/generated/${chunk.name}-chunk.txt`, code],
    [`shared/generated/${chunk.name}-chunk-manifest.ts`, `// Generated by scripts/build-client-chunks.mjs; do not edit.\nexport const ${chunk.manifest} = ${JSON.stringify(manifest)} as const;\n`],
  ];
  for (const [path, content] of outputs) {
    const output = join(root, path);
    if (check) {
      if (await readFile(output, "utf8").catch(() => null) !== content) throw new Error(`${path} is stale. Run npm run build.`);
    } else {
      await mkdir(dirname(output), { recursive: true });
      await writeFile(output, content);
    }
  }
  console.log(`${check ? "Verified" : "Built"} ${chunk.name}: ${manifest.bytes} bytes, ${manifest.hash}`);
}
